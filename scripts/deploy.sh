#!/bin/bash
set -e

echo "🚀 AgentGuard — Build & Deploy to Devnet"
echo "========================================="
echo ""

KEYS_DIR=".keys"
SOLANA_BIN="$HOME/.local/share/solana/install/active_release/bin"
export PATH="$SOLANA_BIN:$PATH"

# Verify prerequisites
if [ ! -f "$KEYS_DIR/deployer.json" ]; then
  echo "❌ Deployer keypair not found. Run 'make setup' first."
  exit 1
fi

DEPLOYER_PUBKEY=$(solana-keygen pubkey "$KEYS_DIR/deployer.json")
echo "  Deployer: $DEPLOYER_PUBKEY"

# Check deployer balance
BALANCE=$(solana balance "$DEPLOYER_PUBKEY" --url devnet 2>/dev/null | awk '{print $1}')
echo "  Balance:  ${BALANCE} SOL"
echo ""

# ── 1. Build Anchor program ──
echo "🔨 Building Anchor program..."
anchor build 2>&1 | tail -5
echo ""

# ── 2. Get program keypair address ──
PROGRAM_KEYPAIR="target/deploy/agentchain_guard-keypair.json"
PROGRAM_ID=$(solana-keygen pubkey "$PROGRAM_KEYPAIR")
echo "  Program ID: $PROGRAM_ID"
echo ""

# ── 3. Deploy to devnet ──
echo "📡 Deploying to Solana Devnet..."
solana program deploy \
  "target/deploy/agentchain_guard.so" \
  --keypair "$KEYS_DIR/deployer.json" \
  --url devnet \
  --program-id "$PROGRAM_KEYPAIR" \
  2>&1 | tail -3
echo ""

# ── 4. Update program ID in source files ──
echo "📝 Updating program ID in source files..."
# Update lib.rs
sed -i '' "s/declare_id!(\"[^\"]*\")/declare_id!(\"$PROGRAM_ID\")/" \
  programs/agentchain-guard/src/lib.rs

# Update Anchor.toml
sed -i '' "s/agentchain_guard = \"[^\"]*\"/agentchain_guard = \"$PROGRAM_ID\"/g" \
  Anchor.toml

# Update SDK constants
sed -i '' "s/export const PROGRAM_ID = new PublicKey('[^']*')/export const PROGRAM_ID = new PublicKey('$PROGRAM_ID')/" \
  packages/sdk/src/constants.ts

# Update config constants
sed -i '' "s/export const PROGRAM_ID = '[^']*'/export const PROGRAM_ID = '$PROGRAM_ID'/" \
  packages/config/src/constants.ts

echo "  ✓ Program ID updated across all packages"
echo ""

# ── 5. Write .env with addresses ──
echo "📋 Writing .env..."
cat > .env <<EOF
# AgentChain Guard — Generated by deploy.sh
SOLANA_RPC_URL=https://api.devnet.solana.com
PROGRAM_ID=$PROGRAM_ID
DEPLOYER_PUBKEY=$DEPLOYER_PUBKEY
AUTHORITY_PUBKEY=$(solana-keygen pubkey $KEYS_DIR/authority.json)
APPROVER_PUBKEY=$(solana-keygen pubkey $KEYS_DIR/approver.json)
AGENT_PUBKEY=$(solana-keygen pubkey $KEYS_DIR/agent.json)
POLICY_ENGINE_PORT=3010
DASHBOARD_PORT=3009
EOF
echo "  ✓ .env written"
echo ""

# ── 6. Summary ──
echo "✅ Deployment Complete"
echo "====================="
echo "  Program:    $PROGRAM_ID"
echo "  Explorer:   https://explorer.solana.com/address/$PROGRAM_ID?cluster=devnet"
echo "  Deployer:   $DEPLOYER_PUBKEY"
echo ""
echo "Next steps:"
echo "  1. Run 'make init-guard' to initialize the Guard program"
echo "  2. Run 'make dev' to start all services"
